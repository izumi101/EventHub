#!/usr/bin/env bash
# Create EventHub/.env for production ON THE SERVER (docs/DEPLOY.md).
#
#   scripts/prod-env.sh                       # SITE_DOMAIN from the VM's public IP via sslip.io
#   scripts/prod-env.sh --domain example.kz   # a real domain (PAY_DOMAIN = pay.example.kz)
#
# Generates every secret with a CSPRNG, asks (silently) for the values only
# the owner knows (SMTP login, SMTP app password, admin password) and leaves
# them empty with a TODO marker when skipped: compose then refuses to start
# until they are filled in. Never prints a secret, writes the file with mode
# 600 and refuses to overwrite an existing .env. Variables are documented in
# deploy/env.production.example.
set -euo pipefail
umask 077
cd "$(dirname "$0")/.."
ENV_FILE=.env

domain=''
while [ $# -gt 0 ]; do
  case "$1" in
    --domain) domain="${2:?--domain needs a host name}"; shift 2 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done

if [ -e "$ENV_FILE" ]; then
  echo "Refusing to overwrite the existing $(pwd)/$ENV_FILE (move it away first if you really mean it)." >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

# Random URL-safe string of $1 characters (no quoting problems in .env).
# (No `head` in the pipes: an early-closed pipe would trip pipefail.)
rand() { local s; s=$(openssl rand -base64 $(( $1 * 2 )) | tr -dc 'A-Za-z0-9'); printf '%s' "${s:0:$1}"; }
rand_digits() { local s; s=$(openssl rand -hex 32 | tr -dc '0-9'); printf '1%s' "${s:0:8}"; }

if [ -z "$domain" ]; then
  ip=$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)
  if [ -z "$ip" ]; then
    read -r -p "Public IPv4 of this VM: " ip
  fi
  [[ "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "Not an IPv4 address: $ip" >&2; exit 1; }
  domain="${ip//./-}.sslip.io"
fi
[[ "$domain" =~ ^[A-Za-z0-9.-]+$ ]] || { echo "Invalid domain: $domain" >&2; exit 1; }

# ask VAR "prompt" [silent]: read a value; empty answer leaves a TODO.
ask() {
  local value=''
  if [ -t 0 ]; then
    if [ "${3:-}" = silent ]; then
      read -r -s -p "$2 (Enter to fill in later): " value; echo
    else
      read -r -p "$2 (Enter to fill in later): " value
    fi
  fi
  printf -v "$1" '%s' "$value"
}

acme_email='' smtp_user='' smtp_password='' admin_password=''
ask acme_email "Email for Let's Encrypt notices (optional)"
ask smtp_user "SMTP login (Gmail address)"
ask smtp_password "SMTP password (Gmail app password)" silent
ask admin_password "Password for the 'admin' superuser" silent
todo() { [ -n "$1" ] || printf '  # TODO(owner): fill in before deploying'; }

unleash_secret=$(rand 32)
cat > "$ENV_FILE" <<EOF
# Generated by scripts/prod-env.sh on $(date -u +%Y-%m-%dT%H:%MZ). Documented in deploy/env.production.example.
SITE_DOMAIN=${domain}
PAY_DOMAIN=pay.${domain}
ACME_EMAIL=${acme_email}
CADDY_LOCAL_CERTS=
PUBLIC_URL_PORT=

DJANGO_SECRET_KEY=$(rand 64)

POSTGRES_DB=eventhub
POSTGRES_USER=eventhub_user
POSTGRES_PASSWORD=$(rand 40)
POSTGRES_APP_USER=eventhub_app
POSTGRES_APP_PASSWORD=$(rand 40)
POSTGRES_READONLY_USER=eventhub_readonly
POSTGRES_READONLY_PASSWORD=$(rand 40)

MFA_ENCRYPTION_KEY=$(rand 64)
MFA_REQUIRED_ROLES=organizer,staff,superuser
MFA_EMAIL_ALLOWED_FOR_REQUIRED_ROLES=1
MFA_STEP_UP_MAX_AGE_SECONDS=600

PAYMENT_PROVIDERS_ENABLED=freedompay
FREEDOMPAY_API_URL=http://fpay-emulator:8080
FREEDOMPAY_MERCHANT_ID=$(rand_digits)
FREEDOMPAY_SECRET_KEY=$(rand 40)
FREEDOMPAY_RESULT_URL=http://backend:8000/api/v1/payments/callback/freedompay/
FREEDOMPAY_TESTING_MODE=1
FREEDOMPAY_DEMO_MODE=1
FPAY_CONTROL_TOKEN=$(rand 40)
STRIPE_SECRET_KEY=
STRIPE_PUBLISHABLE_KEY=
STRIPE_WEBHOOK_SECRET=

EMAIL_HOST=smtp.gmail.com
EMAIL_PORT=587
EMAIL_USE_TLS=1
EMAIL_HOST_USER=${smtp_user}$(todo "$smtp_user")
EMAIL_HOST_PASSWORD=${smtp_password}$(todo "$smtp_password")
DEFAULT_FROM_EMAIL=${smtp_user:+EventHub <${smtp_user}>}$(todo "$smtp_user")
NOTIFICATION_TIME_ZONE=Asia/Almaty
EVENT_DEFAULT_DURATION_HOURS=3

DJANGO_SEED_ADMIN_PASSWORD=${admin_password}$(todo "$admin_password")
DJANGO_SEED_DEMO_PASSWORD=$(rand 16)

INSTALL_SEMANTIC_SEARCH=1
JOBS_RUN_INLINE=0
WEB_CONCURRENCY=2
DJANGO_THROTTLE_RATES=

COMPOSE_PROFILES=
UNLEASH_ENABLED=0
UNLEASH_ENVIRONMENT=production
UNLEASH_DB_PASSWORD=$(rand 32)
UNLEASH_ADMIN_PASSWORD=$(rand 24)
UNLEASH_BACKEND_API_TOKEN=default:production.${unleash_secret}
UNLEASH_ADMIN_API_TOKEN=
EOF
chmod 600 "$ENV_FILE"

# A trailing "  # TODO" comment would become part of the value in .env, so
# move the markers onto their own line above the variable.
tmp=$(mktemp)
awk '/  # TODO\(owner\)/ { sub(/  # TODO\(owner\): fill in before deploying$/, ""); print "# TODO(owner): fill in before deploying"; print; next } { print }' "$ENV_FILE" > "$tmp"
cat "$tmp" > "$ENV_FILE"
rm -f "$tmp"

echo "Wrote $(pwd)/$ENV_FILE (mode 600) for https://${domain} and https://pay.${domain}."
if grep -q '^# TODO(owner)' "$ENV_FILE"; then
  echo "Still to fill in (marked TODO in .env):"
  grep -A1 '^# TODO(owner)' "$ENV_FILE" | grep -v '^#' | grep -v '^--' | cut -d= -f1 | sed 's/^/  - /'
fi
echo "Next: scripts/prod-deploy.sh (docs/DEPLOY.md)."
